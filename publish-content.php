$action = $_GET['action'] ?? 'preview';

if ($action === 'preview') {
    echo "<h1>Предпросмотр контента</h1>";
    echo "<p>Найдено статей: " . count($posts) . "</p>";
    echo "<p><a href='?key={$SECRET_KEY}&action=publish'>🚀 Опубликовать все</a></p><hr>";

    foreach ($posts as $i => $post) {
        echo "<h2>" . ($i+1) . ". {$post['title']}</h2>";
        echo "<p><em>Категория: {$post['category']}</em></p>";
        echo "<div style='background:#f5f5f5;padding:15px;margin:10px 0;'>{$post['content']}</div>";
        echo "<p><a href='?key={$SECRET_KEY}&action=publish_one&index={$i}'>Опубликовать только эту</a></p><hr>";
    }
    exit;
}

if ($action === 'publish' || $action === 'publish_one') {
    $results = [];

    $to_publish = ($action === 'publish_one')
        ? [$posts[intval($_GET['index'] ?? 0)]]
        : $posts;

    foreach ($to_publish as $post) {
        // Получаем или создаём категорию
        $cat = get_category_by_slug(sanitize_title($post['category']));
        if ($cat) {
            $category_id = $cat->term_id;
        } else {
            $category_id = wp_insert_category(['cat_name' => $post['category']]);
        }

        // Создаём пост
        $post_id = wp_insert_post([
            'post_title'    => $post['title'],
            'post_content'  => $post['content'],
            'post_status'   => 'publish',
            'post_author'   => 1,
            'post_category' => [$category_id],
        ]);

        if (!is_wp_error($post_id)) {
            $results[] = [
                'success' => true,
                'title' => $post['title'],
                'post_id' => $post_id,
                'url' => get_permalink($post_id),
            ];
        } else {
            $results[] = [
                'success' => false,
                'title' => $post['title'],
                'error' => $post_id->get_error_message(),
            ];
        }
    }

    echo "<h1>Результаты публикации</h1>";
    foreach ($results as $r) {
        if ($r['success']) {
            echo "<p>✅ <strong>{$r['title']}</strong><br>";
            echo "   → <a href='{$r['url']}' target='_blank'>{$r['url']}</a></p>";
        } else {
            echo "<p>❌ <strong>{$r['title']}</strong>: {$r['error']}</p>";
        }
    }
    echo "<hr><p><a href='" . home_url() . "'>← На главную сайта</a></p>";
}
